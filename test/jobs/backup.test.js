'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { csvValue, restoreSql, exportTables, TABLES } = require('../../src/jobs/backup');
const { createFakeDb } = require('../persistence/fakeDb');

test('csvValue: NULL unquoted, strings quoted (empty ≠ NULL), arrays and json in PostgreSQL form', () => {
  assert.equal(csvValue(null), '');
  assert.equal(csvValue(''), '""');
  assert.equal(csvValue('a "b", c\nd'), '"a ""b"", c\nd"');
  assert.equal(csvValue(2.5), '2.5');
  assert.equal(csvValue(false), 'false');
  assert.equal(csvValue([]), '"{}"');
  assert.equal(csvValue(['A', 'x "y"', null]), '"{""A"",""x \\""y\\"""",NULL}"');
  assert.equal(csvValue({ a: [1, 'x'] }), '"{""a"":[1,""x""]}"');
});

test('export writes every table in FK order with a manifest; restore script checks every count', async () => {
  const db = createFakeDb();
  db.table('teams').push({ id: 't1', name: 'A' }, { id: 't2', name: 'B' });
  db.table('predictions').push({ id: 1, reason_codes: ['X'] });
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fvis-backup-'));
  const m = await exportTables({ db, outDir: dir, now: () => new Date('2026-10-18T02:23:00Z') });
  assert.deepEqual(m.tables.map((t) => t.name), TABLES.map((t) => t.name));
  assert.equal(m.tables.find((t) => t.name === 'teams').rows, 2);
  assert.equal(fs.readFileSync(path.join(dir, 'teams.csv'), 'utf8'), '"t1","A"\n"t2","B"\n');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8')).createdAt, '2026-10-18T02:23:00.000Z');
  const sql = restoreSql(m, dir);
  assert.match(sql, /\\copy public\.teams \("id", "name"\) from '.*teams\.csv' with \(format csv\)/);
  assert.match(sql, /alter table public\.predictions alter column id set generated by default;/);
  assert.match(sql, /count\(\*\) from public\.odds_snapshots\) <> 0/);
  assert.ok(sql.indexOf('public.teams (') < sql.indexOf('public.predictions ('));
  assert.throws(() => restoreSql({ tables: [{ name: 'nope', rows: 1, columns: ['a'] }] }, dir), /unknown table/);
});
