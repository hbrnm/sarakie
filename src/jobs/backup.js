'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { unwrap } = require('../persistence/supabase');

const PAGE = 1000;

/**
 * Tables in foreign-key order (restore loads them in this order), with the columns used for
 * stable paging. `identity`: tables whose `id` is GENERATED ALWAYS AS IDENTITY.
 */
const TABLES = Object.freeze([
  { name: 'competitions', order: ['code'] },
  { name: 'provider_competition_map', order: ['source_provider', 'provider_competition_id'] },
  { name: 'teams', order: ['id'] },
  { name: 'provider_team_map', order: ['source_provider', 'provider_team_ref'] },
  { name: 'fixtures', order: ['id'] },
  { name: 'bookmakers', order: ['id'], identity: true },
  { name: 'odds_events', order: ['source_provider', 'provider_event_id'] },
  { name: 'odds_snapshots', order: ['id'], identity: true },
  { name: 'odds_event_links', order: ['source_provider', 'provider_event_id'] },
  { name: 'provider_request_log', order: ['id'], identity: true },
  { name: 'odds_credit_ledger', order: ['id'], identity: true },
  { name: 'model_versions', order: ['id'], identity: true },
  { name: 'analysis_runs', order: ['id'] },
  { name: 'predictions', order: ['id'], identity: true },
  { name: 'prediction_outcomes', order: ['prediction_id'] },
  { name: 'explanations', order: ['id'], identity: true },
  { name: 'scan_digests', order: ['scan_date'] },
  { name: 'line_candidates', order: ['id'], identity: true },
  { name: 'line_candidate_outcomes', order: ['candidate_id'] },
]);

const quote = (s) => `"${String(s).replace(/"/g, '""')}"`;
const arrayItem = (v) => (v === null ? 'NULL' : `"${String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`);

/**
 * One value in PostgreSQL CSV form: NULL is an unquoted empty field, every string is quoted
 * (so '' stays distinct from NULL), arrays use the array literal syntax, objects are JSON.
 */
function csvValue(v) {
  if (v === null || v === undefined) return '';
  if (Array.isArray(v)) return quote(`{${v.map(arrayItem).join(',')}}`);
  if (typeof v === 'object') return quote(JSON.stringify(v));
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return quote(v);
}

/**
 * Exports every FVIS table to `<outDir>/<table>.csv` (no header) plus `manifest.json`
 * (row counts and column order). Read-only. Tables are read one after another, so the
 * export should run while no job writes (scheduled for Sunday night).
 */
async function exportTables({ db, outDir, now = () => new Date() }) {
  fs.mkdirSync(outDir, { recursive: true });
  const manifest = { createdAt: now().toISOString(), format: 'csv, no header, PostgreSQL COPY compatible', tables: [] };
  for (const t of TABLES) {
    const file = path.join(outDir, `${t.name}.csv`);
    const fd = fs.openSync(file, 'w');
    let columns = null;
    let rows = 0;
    try {
      for (let from = 0; ; from += PAGE) {
        let q = db.from(t.name).select('*');
        for (const c of t.order) q = q.order(c, { ascending: true });
        const page = unwrap(await q.range(from, from + PAGE - 1), `export ${t.name}`);
        if (page.length && !columns) columns = Object.keys(page[0]);
        for (const r of page) fs.writeSync(fd, `${columns.map((c) => csvValue(r[c])).join(',')}\n`);
        rows += page.length;
        if (page.length < PAGE) break;
      }
    } finally {
      fs.closeSync(fd);
    }
    manifest.tables.push({ name: t.name, rows, columns: columns || [] });
  }
  fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;

/**
 * psql script that restores an export into a database where the migrations were applied
 * (and nothing else), then asserts every row count. Used by the weekly restore test and as
 * the documented restore procedure.
 */
function restoreSql(manifest, dir) {
  const lines = ['\\set ON_ERROR_STOP on', 'begin;', 'delete from public.competitions; -- seeded by migration 1, restored from the export'];
  for (const t of manifest.tables) {
    const meta = TABLES.find((x) => x.name === t.name);
    if (!meta) throw new Error(`unknown table in manifest: ${t.name}`);
    if (!t.rows) continue;
    if (meta.identity) lines.push(`alter table public.${t.name} alter column id set generated by default;`);
    const file = path.join(dir, `${t.name}.csv`).replace(/'/g, "''");
    lines.push(`\\copy public.${t.name} (${t.columns.map(ident).join(', ')}) from '${file}' with (format csv)`);
    if (meta.identity) {
      lines.push(`select setval(pg_get_serial_sequence('public.${t.name}', 'id'), (select max(id) from public.${t.name}));`);
      lines.push(`alter table public.${t.name} alter column id set generated always;`);
    }
  }
  for (const t of manifest.tables) {
    lines.push(`do $$ begin if (select count(*) from public.${t.name}) <> ${Number(t.rows)} then raise exception 'restore check failed: ${t.name}'; end if; end $$;`);
  }
  lines.push('commit;', "select 'RESTORE CHECK PASSED' as result;");
  return `${lines.join('\n')}\n`;
}

module.exports = { exportTables, restoreSql, csvValue, TABLES };
